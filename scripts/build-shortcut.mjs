// Builds the iPhone share-sheet shortcut's two parts from the tested code.
//   node scripts/build-shortcut.mjs            rewrites js/shortcut.js (script the shortcut fetches at run time)
//   node scripts/build-shortcut.mjs <out.plist> also writes the unsigned shortcut, to sign with
//     shortcuts sign --mode anyone --input <out.plist> --output chce.shortcut
// js/shortcut.js is generated from js/extract.js; tests/shortcut.test.mjs fails when they drift.
import { writeFileSync } from "node:fs";
import { extract } from "../js/extract.js";

const SITE = "https://anks.pl/chce/";

// Safari's "Run JavaScript on Web Page" runs this text and waits for completion(value).
// A page extract() cannot read still completes, with {}: the add page opens as an empty form.
export function buildScript() {
  return `// Generated by scripts/build-shortcut.mjs from js/extract.js. Do not edit.\n` +
    `(() => {\n  let d = {};\n  try { d = (${extract})(document); } catch (e) {}\n` +
    `  completion(JSON.stringify(d));\n})();\n`;
}

const OBJ = "￼"; // marks where a variable goes inside a text value
const uuid = { fetch: "6A1C0F3E-0B5D-4C3A-9E57-1D2F7B8A4C01", run: "6A1C0F3E-0B5D-4C3A-9E57-1D2F7B8A4C02", enc: "6A1C0F3E-0B5D-4C3A-9E57-1D2F7B8A4C03" };
const out = (name, id) => ({ OutputName: name, OutputUUID: id, Type: "ActionOutput" });
const tokenString = (before, name, id) => ({
  Value: { string: before + OBJ, attachmentsByRange: { [`{${before.length}, 1}`]: out(name, id) } },
  WFSerializationType: "WFTextTokenString",
});
const action = (name, params) => ({ WFWorkflowActionIdentifier: `is.workflow.actions.${name}`, WFWorkflowActionParameters: params });

export function buildPlist() {
  return {
    WFWorkflowActions: [
      action("downloadurl", { UUID: uuid.fetch, WFURL: `${SITE}js/shortcut.js` }),
      action("runjavascriptonwebpage", {
        UUID: uuid.run,
        WFInput: { Value: { Type: "ExtensionInput" }, WFSerializationType: "WFTextTokenAttachment" },
        WFJavaScript: tokenString("", "Contents of URL", uuid.fetch),
      }),
      action("urlencode", {
        UUID: uuid.enc,
        WFEncodeMode: "Encode",
        WFInput: { Value: out("JavaScript Result", uuid.run), WFSerializationType: "WFTextTokenAttachment" },
      }),
      action("openurl", { WFInput: tokenString(`${SITE}add.html#`, "URL Encoded Text", uuid.enc) }),
    ],
    WFWorkflowClientVersion: "900",
    WFWorkflowMinimumClientVersion: 900,
    WFWorkflowMinimumClientVersionString: "900",
    WFWorkflowHasShortcutInputVariables: true,
    WFWorkflowIcon: { WFWorkflowIconStartColor: 4282601983, WFWorkflowIconGlyphNumber: 59771 },
    WFWorkflowImportQuestions: [],
    WFWorkflowInputContentItemClasses: ["WFSafariWebPageContentItem"],
    WFWorkflowTypes: ["ActionExtension"],
  };
}

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function xml(v, pad) {
  if (Array.isArray(v)) return v.length ? `<array>\n${v.map((x) => pad + "\t" + xml(x, pad + "\t")).join("\n")}\n${pad}</array>` : "<array/>";
  if (typeof v === "string") return `<string>${esc(v)}</string>`;
  if (typeof v === "boolean") return v ? "<true/>" : "<false/>";
  if (typeof v === "number") return `<integer>${v}</integer>`;
  const rows = Object.entries(v).map(([k, x]) => `${pad}\t<key>${esc(k)}</key>\n${pad}\t${xml(x, pad + "\t")}`);
  return `<dict>\n${rows.join("\n")}\n${pad}</dict>`;
}
export const plistXml = () =>
  `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n${xml(buildPlist(), "")}\n</plist>\n`;

if (process.argv[1] === new URL(import.meta.url).pathname) {
  writeFileSync(new URL("../js/shortcut.js", import.meta.url), buildScript());
  if (process.argv[2]) writeFileSync(process.argv[2], plistXml());
}
